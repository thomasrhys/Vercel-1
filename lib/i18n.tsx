const translations: Record<Language, TranslationMap> = { en: english, cy: welsh };

type LanguageContextValue = { language: Language; setLanguage: (language: Language) => void };
const LanguageContext = createContext<LanguageContextValue>({ language: "en", setLanguage: () => undefined });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("site-language");
    const next = saved === "cy" || saved === "en" ? saved : "en";
    setLanguageState(next);
    document.documentElement.lang = next;
  }, []);
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem("site-language", next);
    document.documentElement.lang = next;
  };
  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() { return useContext(LanguageContext); }

export function t(key: string) {
  const language = typeof window !== "undefined" && window.localStorage.getItem("site-language") === "cy" ? "cy" : "en";
  return translations[language][key] ?? key;
}
